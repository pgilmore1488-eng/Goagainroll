function frictionOf([time, death, restriction, maintenance, variance]) {
  return time + death + 3 * restriction + 2 * maintenance + variance
}

function difficultyOf(name, parts, fallback) {
  if (name === 'Self Found') return 'Self Found'
  if (DIFFICULTY_OVERRIDE[name]) return DIFFICULTY_OVERRIDE[name]
  const death = parts[1]
  if (death >= 30) return 'insane'
  if (death >= 20) return 'hard'
  if (death >= 10) return 'medium'
  return 'easy'
}

function toRow(base) {
  const name = base.Affix
  const parts = SCORES[name]
  if (!parts) throw new Error(`Missing score for ${name}`)
  const [time, death, restriction, maintenance, variance] = parts
  return {
    Affix: name,
    Category: base.Category,
    Class: base.Class,
    Spec: base.Spec,
    Difficulty: difficultyOf(name, parts, base.Difficulty),
    Description: DESCRIPTIONS[name] || base.Description,
    'Sub Roll': base['Sub Roll'] || '',
    'Sub Roll Friction': SUB_ROLL_FRICTION[name] || base['Sub Roll Friction'] || '',
    Friction: frictionOf(parts),
    'Time points': time,
    'Death-risk points': death,
    'Restriction level': restriction,
    'Maintenance level': maintenance,
    'Variance level': variance,
    'Exclusion Group': EXCLUSION_UPDATES[name] ?? base['Exclusion Group'] ?? '',
  }
}

